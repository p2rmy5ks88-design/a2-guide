const assert=require('node:assert/strict');
const W=require('../lib/weekly-challenges.js');
const monday=Date.parse('2026-11-16T00:00:00Z');
assert.equal(W.weekStart(Date.parse('2026-11-22T23:59:59Z')),monday);
assert.equal(W.weekStart(Date.parse('2026-11-23T00:00:00Z')),monday+7*86400000);
let s=W.fresh(monday);
assert.equal(s.week,monday);
assert.equal(W.record(s,{type:'match_completed'},monday).counts.matches,0);
s=W.record(s,{type:'match_completed',eligible:true,id:'match-0'},monday);
assert.equal(s.counts.matches,1);
s=W.record(s,{type:'match_completed',eligible:true,id:'match-0'},monday);
assert.equal(s.counts.matches,1);
assert.equal(W.record(s,{type:'match_completed',eligible:true},monday).counts.matches,1);
assert.equal(W.claim(s,'matches',monday).reward,null);
for(let i=0;i<5;i++)s=W.record(s,{type:'match_completed',eligible:true,id:'match-'+(i+1)},monday);
assert.equal(s.counts.matches,3);
let result=W.claim(s,'matches',monday);
assert.equal(result.reward.amount,30);
assert.equal(W.claim(result.state,'matches',monday).reward,null);
assert.equal(W.record(result.state,{type:'property_purchased',eligible:true,id:'property-1'},monday).counts.properties,1);
assert.equal(W.record(result.state,{type:'harbour_ring_completed',eligible:true,id:'duel-1'},monday).counts.duel,1);
assert.equal(W.view(result.state,monday).objectives[0].claimed,true);
assert.equal(W.normalize(result.state,monday+7*86400000).counts.matches,0);
assert.equal(W.normalize({version:1,week:monday,counts:{matches:999,properties:-3},claimed:['matches','properties']},monday).claimed.join(','),'matches');
assert.throws(()=>W.weekStart(NaN));
console.log('PASS weekly challenge foundation: 16 assertions');
