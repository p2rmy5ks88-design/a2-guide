const assert=require('node:assert/strict');
const U=require('../lib/weekly-contracts-summary.js');
const defs=[{id:'games5',n:'Finish 5 games',g:5},{id:'wins3',n:'Win 3 games',g:3},{id:'rent3000',n:'Collect rent',g:3000}];
const state={list:['games5','wins3','rent3000'],prog:{games5:2,wins3:5,rent3000:-3},done:{wins3:1}};
const before=JSON.stringify(state);
const s=U.summary(state,defs);
assert.equal(s.total,3);
assert.equal(s.completed,1);
assert.equal(s.entries[0].progress,2);
assert.equal(s.entries[1].progress,3);
assert.equal(s.entries[2].progress,0);
assert.equal(JSON.stringify(state),before);
const html=U.markup(s);
assert.match(html,/Weekly contracts/);
assert.match(html,/1 \/ 3 complete/);
assert.match(html,/Finish 5 games/);
assert.doesNotMatch(html,/<button/);
const escaped=U.markup(U.summary({list:['games5'],prog:{},done:{}},[{id:'games5',n:'<img src=x>',g:1}]));
assert.match(escaped,/&lt;img/);
assert.doesNotMatch(escaped,/<img/);
assert.throws(()=>U.summary(null,defs));
console.log('PASS existing weekly summary: 13 assertions');
