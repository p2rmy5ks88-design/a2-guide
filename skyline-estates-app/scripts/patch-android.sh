#!/usr/bin/env bash
# Landscape-only, full screen, and version numbers for the Android project made by `npx cap add android`.
set -euo pipefail
cd "$(dirname "$0")/.."
M=android/app/src/main/AndroidManifest.xml
grep -q screenOrientation "$M" || sed -i.bak 's/<activity/<activity android:screenOrientation="sensorLandscape" android:resizeableActivity="true"/' "$M"
grep -q 'screenOrientation="sensorLandscape"' "$M" || { echo "Landscape lock not applied to $M"; exit 1; }
rm -f "$M.bak"
S=android/app/src/main/res/values/styles.xml
if ! grep -q windowFullscreen "$S"; then
  sed -i.bak 's#<style name="AppTheme.NoActionBar" parent="Theme.AppCompat.DayNight.NoActionBar">#&\n        <item name="android:windowFullscreen">true</item>\n        <item name="android:windowLayoutInDisplayCutoutMode">shortEdges</item>#' "$S"; rm -f "$S.bak"
fi
# Immersive full screen: hide the navigation/gesture bar (swipe from the edge shows it briefly), so it never covers
# buttons at the bottom of the landscape game. Target API 35+ draws apps edge to edge, and the WebView does not
# reliably report the gesture-bar inset, so results and menus could run under it.
MA="$(find android/app/src/main/java -name MainActivity.java | head -1)"
[ -n "$MA" ] || { echo "MainActivity.java not found"; exit 1; }
PKG="$(sed -n -E 's/^package ([a-zA-Z0-9_.]+);/\1/p' "$MA")"
cat > "$MA" <<JAVA
package $PKG;

import android.os.Bundle;
import androidx.core.view.WindowCompat;
import androidx.core.view.WindowInsetsCompat;
import androidx.core.view.WindowInsetsControllerCompat;
import com.getcapacitor.BridgeActivity;

public class MainActivity extends BridgeActivity {
    @Override
    public void onCreate(Bundle savedInstanceState) {
        super.onCreate(savedInstanceState);
        immersive();
    }

    @Override
    public void onWindowFocusChanged(boolean hasFocus) {
        super.onWindowFocusChanged(hasFocus);
        if (hasFocus) immersive();
    }

    private void immersive() {
        WindowInsetsControllerCompat bars = WindowCompat.getInsetsController(getWindow(), getWindow().getDecorView());
        bars.setSystemBarsBehavior(WindowInsetsControllerCompat.BEHAVIOR_SHOW_TRANSIENT_BARS_BY_SWIPE);
        bars.hide(WindowInsetsCompat.Type.systemBars());
    }
}
JAVA
grep -q 'Type.systemBars()' "$MA" || { echo "Immersive mode not applied"; exit 1; }
G=android/app/build.gradle
# Keep the Java namespace generated by Capacitor and use the existing Play listing's application ID.
APP_ID="$(node --input-type=module -e "import {registeredApps} from './scripts/native-firebase-config.mjs'; console.log(registeredApps.androidPackage)")"
sed -i.bak -E "s/^([[:space:]]*applicationId )[\"][-._a-zA-Z0-9]+[\"]/\1\"$APP_ID\"/" "$G"
rm -f "$G.bak"
grep -Fq "applicationId \"$APP_ID\"" "$G" || { echo "Play application ID not applied"; exit 1; }
VC="${VERSION_CODE:-1}"; VN="${VERSION_NAME:-1.0.0}"
sed -i.bak -E "s/versionCode [0-9]+/versionCode ${VC}/; s/versionName \"[^\"]*\"/versionName \"${VN}\"/" "$G"; rm -f "$G.bak"
# Google Play: target API 36 (Android 16), required for app updates from 31 Aug 2026.
V=android/variables.gradle
# Minimum Android 7.0 (API 24): required by Google Play's Automatic protection; Android 6 devices are no longer supported.
sed -i.bak -E "s/compileSdkVersion = [0-9]+/compileSdkVersion = 36/; s/targetSdkVersion = [0-9]+/targetSdkVersion = 36/; s/minSdkVersion = [0-9]+/minSdkVersion = 24/" "$V"; rm -f "$V.bak"
grep -q 'targetSdkVersion = 36' "$V" || { echo "targetSdk 36 not applied"; exit 1; }
grep -q 'minSdkVersion = 24' "$V" || { echo "minSdk 24 not applied"; exit 1; }
grep -q suppressUnsupportedCompileSdk android/gradle.properties || echo 'android.suppressUnsupportedCompileSdk=36' >> android/gradle.properties
node scripts/native-firebase-config.mjs android
echo "Android patched: landscape, immersive full screen, min API 24, target API 36, versionCode ${VC}, versionName ${VN}"
