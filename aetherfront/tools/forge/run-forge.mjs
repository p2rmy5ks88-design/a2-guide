// Regenerates assets/models/*.glb (v2 animated) + assets/portraits/*.png from catalog.js
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { serve } from '../serve.mjs';
import { launch } from '../browser.mjs';
const AF = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const manifestPath = path.join(AF, 'data', 'asset_manifest.json');
const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
const server = await serve(8791);
const browser = await launch();
const page = await browser.newPage({ viewport: { width: 1260, height: 1500 } });
page.on('console', (m) => m.type() === 'error' && console.error('[page]', m.text()));
page.on('pageerror', (e) => console.error('[pageerror]', e.message));
await page.goto('http://127.0.0.1:8791/aetherfront/tools/forge/forge.html');
await page.waitForFunction(() => window.forgeReady === true, null, { timeout: 30000 });
const ids = await page.evaluate(() => window.forgeIds());
fs.mkdirSync(path.join(AF, 'assets', 'portraits'), { recursive: true });
const byId = Object.fromEntries([...manifest.units, ...manifest.environment].map((u) => [u.id, u]));
const sheet = [];
let total = 0;
for (const id of ids) {
  const r = await page.evaluate((id) => window.forgeGLB(id), id);
  fs.writeFileSync(path.join(AF, 'assets', 'models', id + '.glb'), Buffer.from(r.b64, 'base64'));
  total += r.bytes;
  const rec = byId[id];
  if (rec) Object.assign(rec, { model: `assets/models/${id}.glb`, starter_model: `assets/models/starter/${id}.glb`, model_version: 2, bounds: r.bounds, triangles: r.tris, animation_clips: r.clips });
  delete rec?.primitives;
  if (rec && rec.category) {
    const humanoid = rec.category === 'hero' || (['unit'].includes(rec.category) && !['aether_drone_swarm', 'halo_medic', 'atlas_walker'].includes(id)) || ['titan_breaker'].includes(id);
    const url = await page.evaluate(([id, k]) => window.portrait(id, k), [id, humanoid ? 'humanoid' : 'object']);
    fs.writeFileSync(path.join(AF, 'assets', 'portraits', id + '.png'), Buffer.from(url.split(',')[1], 'base64'));
    rec.portrait = `assets/portraits/${id}.png`;
    sheet.push([id, url]);
  }
  console.log(id.padEnd(22), (r.bytes / 1024).toFixed(1).padStart(7), 'KB', String(r.tris).padStart(6), 'tris', r.clips.join(','));
}
manifest.version = '0.2.0-forge-v2';
manifest.asset_status = 'FORGE v2: original animated rigid-rig GLB models (idle/move/fire/hit/die clips, PBR vertex-colour + unlit emissive materials) generated by tools/forge; starter v1 GLBs kept in assets/models/starter/. Still stylised low-poly, NOT final hand-sculpted production art.';
fs.writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + '\n');
await page.evaluate((s) => window.sheet(s), sheet);
await page.waitForTimeout(500);
fs.mkdirSync(path.join(AF, 'test-results'), { recursive: true });
await page.screenshot({ path: path.join(AF, 'test-results', 'forge-contact-sheet.png'), fullPage: true });
console.log('TOTAL', (total / 1024).toFixed(0), 'KB for', ids.length, 'models');
await browser.close(); server.close();
